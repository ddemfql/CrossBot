"""Persistence interfaces used by workflow modules."""
from __future__ import annotations

from typing import Protocol
from core.models import AuditEvent, Case, CrossCheckResult, Document, ReviewTask

class CaseStore(Protocol):
    def save_case(self, case: Case) -> None: ...
    def get_case(self, case_id: str) -> Case | None: ...
    def save_document(self, document: Document) -> None: ...
    def get_document(self, document_id: str) -> Document | None: ...
    def save_review_task(self, task: ReviewTask) -> None: ...
    def save_cross_check(self, result: CrossCheckResult) -> None: ...
    def append_audit(self, event: AuditEvent) -> None: ...
