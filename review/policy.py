"""Shared authorization and version invalidation for the W3 services.

Actor objects must come from the application authentication boundary. A role
selector or a caller-supplied user name is not an authentication mechanism.
"""
from __future__ import annotations

import hashlib
import json
from contextvars import ContextVar
from core.errors import CrossBotError, ErrorCode
from core.models import (Actor, AuditEvent, CaseStatus, CrossCheckStatus,
                         Workspace, to_dict, utc_now)

ROLES = frozenset({"sales", "admin"})
authorization_boundary = ContextVar("w3_authorization_boundary", default=None)
# Business users handle every transaction operation themselves. Provisioning
# accounts remains an administrator responsibility at the identity/UI boundary.
PERMISSIONS = {action: ROLES for action in (
    "create", "update_trade", "edit_trade", "confirm_trade", "upload", "parse",
    "generate", "confirm_field", "manual_field", "delete_document", "approve",
    "return", "milestone", "payment", "close", "handoff", "check", "view", "download",
)}
PERMISSIONS["template_manage"] = frozenset({"admin"})


def audit(workspace: Workspace, actor: Actor, action: str, entity_type: str = "",
          entity_id: str = "", before=None, after=None, reason: str = "") -> None:
    workspace.audit.append(AuditEvent(
        case_id=workspace.case.case_id,
        actor_id=actor.user_id or "unauthenticated", action=action,
        entity_type=entity_type, entity_id=entity_id,
        before=before, after=after, reason=reason))
    workspace.case.updated_at = utc_now()


def require(workspace: Workspace | None, actor: Actor, action: str) -> None:
    boundary = authorization_boundary.get()
    if boundary is not None:
        boundary(workspace, actor, action)
    allowed = PERMISSIONS.get(action, frozenset())
    authenticated = (isinstance(actor, Actor) and actor.authenticated
                     and actor.kind == "human" and bool(actor.user_id.strip()))
    authorized = authenticated and bool(set(actor.roles) & allowed)
    if not authorized:
        if workspace is not None:
            audit(workspace, actor, "access_denied", "case", workspace.case.case_id,
                  after={"action": action}, reason="身份或岗位无权执行此操作")
        raise CrossBotError(ErrorCode.FORBIDDEN, "请以有权限的真人账号登录后执行此操作。")
    if (workspace is not None and workspace.case.status is CaseStatus.CLOSED
            and action not in {"view", "download"}):
        raise CrossBotError(ErrorCode.CONFLICT, "已关闭订单不可修改，请保留原有归档记录。")


def invalidate(workspace: Workspace, actor: Actor, reason: str) -> None:
    """Invalidate applicability while retaining every prior approval and output."""
    changed = []
    for artifact in workspace.artifacts:
        if artifact.status in {"draft", "approved"}:
            artifact.status = "stale"
            changed.append(artifact.artifact_id)
    workspace.checks = []
    workspace.case.cross_check_result_ids = []
    if workspace.case.status is CaseStatus.PASSED:
        workspace.case.status = CaseStatus.PENDING_REVIEW
    audit(workspace, actor, "review_invalidated", "case", workspace.case.case_id,
          after={"stale_artifact_ids": changed}, reason=reason)


def source_versions(workspace: Workspace) -> dict[str, str]:
    return {d.document_id: d.current_version_id for d in workspace.documents
            if d.current_version_id is not None and d.deleted_at is None}


def current_artifacts(workspace: Workspace):
    versions = source_versions(workspace)
    return [a for a in workspace.artifacts
            if a.status in {"draft", "approved"}
            and a.input_revision == workspace.trade.revision
            and a.input_snapshot == to_dict(workspace.trade)
            and a.source_versions == versions
            and artifact_form_is_current(workspace, a)
            and any(c.required for c in a.checks)
            and all(c.status is CrossCheckStatus.PASS for c in a.checks if c.required)]


def artifact_form_is_current(workspace: Workspace, artifact) -> bool:
    """Bind generated bytes to the exact human-confirmed form revision."""
    strict_receipts = [event for event in workspace.audit if event.action == "simple_export_confirmed"
        and event.entity_id == artifact.artifact_id and isinstance(event.after, dict)
        and event.after.get("strict_review") is True]
    if artifact.template_id == "simple-xlsx" or strict_receipts:
        from validation.export_review import RULE_VERSION, review_digest
        if artifact.rule_version != RULE_VERSION:
            return False
        digest = review_digest(workspace, artifact.document_type)
        receipt = any(event.action == "simple_export_confirmed"
            and event.entity_id == artifact.artifact_id and isinstance(event.after, dict)
            and event.after.get("strict_review") is True
            and event.after.get("human_confirmed") is True
            and event.after.get("sha256") == artifact.sha256
            and event.after.get("form_revision") == artifact.form_revision
            and event.after.get("rule_version") == RULE_VERSION
            and event.after.get("review_input_digest") == digest for event in strict_receipts)
        if not receipt:
            return False
    if not artifact.form_revision:
        return not artifact.form_snapshot
    form = next((form for form in workspace.document_forms
                 if form.document_type is artifact.document_type), None)
    if not (form and form.revision == artifact.form_revision
            and to_dict(form) == artifact.form_snapshot):
        return False
    if form.confirmed_by and form.confirmed_at:
        return True
    # Strict export confirmation reviews this exact saved snapshot without
    # rewriting raw source fields or impersonating a separate form approval.
    return any(event.action == "simple_export_confirmed"
        and event.entity_id == artifact.artifact_id and isinstance(event.after, dict)
        and event.after.get("strict_review") is True
        and event.after.get("human_confirmed") is True
        and event.after.get("sha256") == artifact.sha256
        and event.after.get("form_revision") == artifact.form_revision
        and event.after.get("rule_version") == artifact.rule_version
        and bool(event.after.get("review_input_digest")) for event in workspace.audit)


def checks_digest(checks) -> str:
    values = []
    for check in checks:
        item = to_dict(check)
        item.pop("result_id", None)
        item.pop("checked_at", None)
        values.append(item)
    payload = json.dumps(values, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def has_current_approval(workspace: Workspace, checks=None) -> bool:
    if not workspace.approvals or not workspace.trade.confirmed_by:
        return False
    approval = workspace.approvals[-1]
    artifacts = current_artifacts(workspace)
    hashes = {a.artifact_id: a.sha256 for a in artifacts}
    return (approval.input_revision == workspace.trade.revision
            and approval.document_versions == source_versions(workspace)
            and approval.artifact_hashes == hashes
            and all(a.status == "approved" for a in artifacts)
            and approval.checks_sha256 == checks_digest(workspace.checks if checks is None else checks))

